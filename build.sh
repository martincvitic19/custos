# Build a Custos image. Custos is an OpenWrt feed; run this from the
# OpenWrt source tree after adding the feed (see README.md):
#
#   ./feeds/custos/build.sh <device> [make args...]
#   ./feeds/custos/build.sh list
#
# <device> is a file name (without .config) from configs/.
#
# Per-build settings (environment variables, all optional):
#   CUSTOS_IP            address/prefix of Custos on the ISP router's network
#                        (default 192.168.0.14/24)
#   CUSTOS_GATEWAY       the ISP router (default: .1 in CUSTOS_IP's network)
#   CUSTOS_HOSTNAME      host name                     (default Custos)
#   CUSTOS_TZ            IANA zone, e.g. Europe/Zagreb (default: build host's)
#   CUSTOS_SSH_PUBKEY    public key file baked into /etc/dropbear/authorized_keys;
#                        when set, SSH password login is disabled
#   CUSTOS_ROOT_PASSWORD root password; a random one is generated when unset
#   CUSTOS_RELEASE=1     build a public release image: no root password (set
#                        it at the first login), no SSH key, time zone UTC
#                        unless CUSTOS_TZ is set
#
# The settings are applied on the first boot only. Later updates that keep
# settings leave the address, password, host name and time zone alone.
#
# Secrets never enter git: the image overlay goes to files/ (ignored by
# OpenWrt) and the generated password to .secrets/ in this feed (ignored).
set -eu

CU="$(cd "$(dirname "$0")" && pwd)"
# The OpenWrt tree: the current directory, or two levels up (feeds/custos).
if [ -f rules.mk ] && [ -d scripts ]; then
	TOPDIR="$(pwd)"
else
	TOPDIR="$(cd "$(dirname "$0")/../.." && pwd)"
fi
[ -f "$TOPDIR/rules.mk" ] || { echo "Run this from the OpenWrt source tree" >&2; exit 1; }
cd "$TOPDIR"
SECRETS="${CU#"$TOPDIR"/}/.secrets"

if [ "${1:-}" = "" ] || [ "$1" = "list" ]; then
	echo "Usage: $0 <device> [make args]"
	echo "Devices:"
	ls "$CU/configs" | sed -n 's/\.config$//p' | grep -v '^common$' | sed 's/^/  /'
	exit 0
fi

DEVICE="$1"; shift
DEVCFG="$CU/configs/$DEVICE.config"
[ -f "$DEVCFG" ] || { echo "Unknown device '$DEVICE' (see: $0 list)" >&2; exit 1; }

IP="${CUSTOS_IP:-192.168.0.14/24}"
case "$IP" in */*) ;; *) IP="$IP/24" ;; esac
GW="${CUSTOS_GATEWAY:-$(echo "${IP%/*}" | sed 's/\.[0-9]*$/.1/')}"
HOSTNAME="${CUSTOS_HOSTNAME:-Custos}"
RELEASE="${CUSTOS_RELEASE:-}"
if [ -n "$RELEASE" ]; then
	[ -z "${CUSTOS_ROOT_PASSWORD:-}${CUSTOS_SSH_PUBKEY:-}" ] ||
		{ echo "CUSTOS_RELEASE: unset CUSTOS_ROOT_PASSWORD and CUSTOS_SSH_PUBKEY" >&2; exit 1; }
	TZNAME="${CUSTOS_TZ:-UTC}"
else
	TZNAME="${CUSTOS_TZ:-$(cat /etc/timezone 2>/dev/null || echo UTC)}"
fi
TZPOSIX="$(tail -n1 "/usr/share/zoneinfo/$TZNAME" 2>/dev/null || echo UTC0)"

echo "==> Custos build: $DEVICE  (address $IP, ISP router $GW, TZ $TZNAME)"

# --- feeds -----------------------------------------------------------------
if [ ! -d feeds/packages ] || [ ! -d feeds/luci ]; then
	./scripts/feeds update -a
fi
if [ ! -e package/feeds/custos/custos ] || [ ! -e package/feeds/luci/luci-base ]; then
	./scripts/feeds install -a
fi

# --- config ----------------------------------------------------------------
cat "$DEVCFG" "$CU/configs/common.config" > .config
make defconfig >/dev/null
for p in custos luci-app-custos adguardhome; do
	grep -q "^CONFIG_PACKAGE_$p=y" .config || { echo "Package $p missing after defconfig" >&2; exit 1; }
done

# --- per-build overlay (files/ is git-ignored) -----------------------------
mkdir -p "$CU/.secrets" files/etc/uci-defaults
chmod 700 "$CU/.secrets"

SET_PW=""
if [ -n "$RELEASE" ]; then
	echo "==> Release build: no root password, no SSH key"
else
	PW="${CUSTOS_ROOT_PASSWORD:-}"
	if [ -z "$PW" ]; then
		PW="$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-16)"
		printf '%s\n' "$PW" > "$CU/.secrets/$DEVICE-root-password"
		chmod 600 "$CU/.secrets/$DEVICE-root-password"
		echo "==> Generated root password -> $SECRETS/$DEVICE-root-password"
	fi
	PWHASH="$(printf '%s' "$PW" | openssl passwd -6 -stdin)"
	SET_PW="sed -i 's|^root:[^:]*:|root:$PWHASH:|' /etc/shadow"
fi

SSH_HARDEN=""
rm -f files/etc/dropbear/authorized_keys
if [ -n "${CUSTOS_SSH_PUBKEY:-}" ]; then
	mkdir -p files/etc/dropbear
	cp "$CUSTOS_SSH_PUBKEY" files/etc/dropbear/authorized_keys
	chmod 600 files/etc/dropbear/authorized_keys
	SSH_HARDEN="set dropbear.@dropbear[0].PasswordAuth='off'
	set dropbear.@dropbear[0].RootPasswordAuth='off'
	commit dropbear"
	echo "==> SSH key baked in, password SSH login disabled"
fi

# leftovers of older builds would run on the device too
rm -f files/etc/uci-defaults/*nestguard* files/etc/uci-defaults/*custos*
# The marker survives sysupgrade, so the settings below are applied once.
mkdir -p files/lib/upgrade/keep.d
echo /etc/custos-site.done > files/lib/upgrade/keep.d/custos-site
# 10-: runs before the package's 90-custos, which applies the address
cat > files/etc/uci-defaults/10-custos-site <<EOF
#!/bin/sh
# Generated by build.sh (Custos feed), applied on the first boot only.
[ -f /etc/custos-site.done ] && exit 0
$SET_PW
uci -q batch <<-EOT
	set custos.connection.ipaddr='$IP'
	set custos.connection.gateway='$GW'
	commit custos
	set system.@system[0].hostname='$HOSTNAME'
	set system.@system[0].zonename='$TZNAME'
	set system.@system[0].timezone='$TZPOSIX'
	commit system
	$SSH_HARDEN
EOT
touch /etc/custos-site.done
exit 0
EOF

# --- build -----------------------------------------------------------------
make download -j8
make -j"$(nproc)" "$@"

echo "==> Images:"
ls -1 bin/targets/*/*/*-sysupgrade.* bin/targets/*/*/*-factory.* 2>/dev/null | sed 's/^/  /'
echo "==> After flashing: https://${IP%/*}/"
